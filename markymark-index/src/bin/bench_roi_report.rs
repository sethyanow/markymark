use markymark_index::{
    parse_mean_ms_from_estimates, parse_memory_snapshot, render_tier_report, MemorySnapshot,
    ScaleRow, TierSummary,
};
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("bench-roi-report: {err}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let sample_tier = env::var("MARKYMARK_BENCH_SAMPLES").unwrap_or_else(|_| "light".to_string());
    let doc_tiers = env::var("MARKYMARK_ROI_TIERS")
        .unwrap_or_else(|_| "light,medium,heavy,extreme".to_string());
    let output_path = env::var("MARKYMARK_ROI_REPORT")
        .unwrap_or_else(|_| "docs/benchmarks/roi-tier-report.md".to_string());

    let workspace_root = workspace_root()?;
    let criterion_root = workspace_root.join("target/criterion/synthetic_scale");

    let mut summaries = Vec::new();
    let mut memory_rows: Vec<(String, MemorySnapshot)> = Vec::new();

    for tier in doc_tiers
        .split(',')
        .map(str::trim)
        .filter(|t| !t.is_empty())
    {
        if criterion_root.exists() {
            let _ = fs::remove_dir_all(&criterion_root);
        }

        run_bench(
            &workspace_root,
            tier,
            &sample_tier,
            "synthetic_scale",
            &["synthetic_scale"],
        )?;

        let mut rows = Vec::new();
        for &doc_count in doc_counts_for_tier(tier) {
            let estimate_path = workspace_root.join(format!(
                "target/criterion/synthetic_scale/{}_docs/new/estimates.json",
                doc_count
            ));
            let json = fs::read_to_string(&estimate_path)
                .map_err(|e| format!("failed reading {}: {e}", estimate_path.display()))?;
            let mean_ms = parse_mean_ms_from_estimates(&json)
                .ok_or_else(|| format!("failed parsing mean from {}", estimate_path.display()))?;
            rows.push(ScaleRow { doc_count, mean_ms });
        }
        summaries.push(TierSummary {
            tier: tier.to_string(),
            rows,
        });

        let memory_out = run_bench(&workspace_root, tier, &sample_tier, "memory", &["memory/"])?;
        let snapshot = parse_memory_snapshot(&memory_out);
        memory_rows.push((tier.to_string(), snapshot));
    }

    let mut markdown = render_tier_report(&summaries, &sample_tier);
    markdown.push('\n');
    markdown.push_str("## Memory Snapshot (index_100)\n\n");
    markdown.push_str("| Tier | Heap alloc count | Resident (MiB) | Peak RSS (KB) |\n");
    markdown.push_str("|------|-----------------:|---------------:|--------------:|\n");
    for (tier, snapshot) in memory_rows {
        markdown.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            tier, snapshot.alloc_count, snapshot.resident_mib, snapshot.peak_rss_kb
        ));
    }
    markdown.push('\n');
    markdown.push_str("_Generated by `cargo run -p markymark-index --bin bench_roi_report`._\n");

    let report_path = workspace_root.join(output_path);
    if let Some(parent) = report_path.parent() {
        fs::create_dir_all(parent)
            .map_err(|e| format!("failed creating {}: {e}", parent.display()))?;
    }
    fs::write(&report_path, markdown)
        .map_err(|e| format!("failed writing {}: {e}", report_path.display()))?;

    println!("Wrote {}", report_path.display());
    Ok(())
}

fn workspace_root() -> Result<PathBuf, String> {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    manifest_dir
        .parent()
        .map(Path::to_path_buf)
        .ok_or_else(|| "could not determine workspace root".to_string())
}

fn run_bench(
    workspace_root: &Path,
    doc_tier: &str,
    sample_tier: &str,
    label: &str,
    args: &[&str],
) -> Result<String, String> {
    eprintln!("Running {label} tier={doc_tier} samples={sample_tier}...");

    let output = Command::new("cargo")
        .arg("bench")
        .arg("-p")
        .arg("markymark-index")
        .arg("--bench")
        .arg("memory")
        .arg("--")
        .args(args)
        .arg("--nocapture")
        .env("MARKYMARK_BENCH_DOC_TIER", doc_tier)
        .env("MARKYMARK_BENCH_SAMPLES", sample_tier)
        .current_dir(workspace_root)
        .output()
        .map_err(|e| format!("failed running cargo bench: {e}"))?;

    let mut combined = String::new();
    combined.push_str(&String::from_utf8_lossy(&output.stdout));
    combined.push('\n');
    combined.push_str(&String::from_utf8_lossy(&output.stderr));

    if !output.status.success() {
        return Err(format!("benchmark command failed:\n{combined}"));
    }
    Ok(combined)
}

fn doc_counts_for_tier(tier: &str) -> &'static [usize] {
    match tier {
        "light" => &[100],
        "medium" => &[100, 1_000],
        "heavy" => &[100, 1_000, 5_000],
        "extreme" => &[100, 1_000, 5_000, 10_000],
        _ => &[100, 1_000],
    }
}
